export const getComprehensionLevelsForClass = (classNumber) => {
  const normalizedClass = String(classNumber || "1").replace(/^Class\s*/i, "").trim();
  const classKey = [1, 2, 3, 4, 5].includes(Number(normalizedClass)) ? Number(normalizedClass) : 1;
  const classData = classComprehensionBank[classKey] || classComprehensionBank[1];
  return [classData[1], classData[2]].map((level) => {
    const shuffledQuestions = level.questions.map((q) => {
      const shuffledOpts = [...(q.options || [])];
      for (let i = shuffledOpts.length - 1; i > 0; i--) {
        const j = Math.floor(Math.random() * (i + 1));
        [shuffledOpts[i], shuffledOpts[j]] = [shuffledOpts[j], shuffledOpts[i]];
      }
      return {
        ...q,
        options: shuffledOpts,
      };
    });
    for (let i = shuffledQuestions.length - 1; i > 0; i--) {
      const j = Math.floor(Math.random() * (i + 1));
      [shuffledQuestions[i], shuffledQuestions[j]] = [shuffledQuestions[j], shuffledQuestions[i]];
    }
    return {
      ...level,
      questions: shuffledQuestions,
    };
  });
};
